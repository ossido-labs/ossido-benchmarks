//! Throughput report: RESULTS.md + results.json. Ported from `report.ts`,
//! preserving section order, table shapes, the mermaid charts, and the
//! `ossido-benchmark/results@1` JSON schema.

use std::collections::HashMap;

use anyhow::Result;
use serde::Serialize;

use crate::config::{load_scenarios, stream_scenario, FrameworkKey, ThreadMode, Versions};
use crate::load::{LoadResult, StreamResult};

pub struct LoadRecord {
    pub framework: FrameworkKey,
    pub mode: ThreadMode,
    pub threads: usize,
    pub scenario: String,
    pub result: LoadResult,
}

pub struct StreamRecord {
    pub framework: FrameworkKey,
    pub mode: ThreadMode,
    pub threads: usize,
    pub result: StreamResult,
}

pub struct BenchReport {
    pub generated_at: String,
    pub cores: usize,
    pub host: String,
    pub cpu_model: String,
    pub total_mem_gb: f64,
    pub connections: usize,
    pub duration_sec: u64,
    pub warmup_sec: u64,
    pub versions: Versions,
    pub load_records: Vec<LoadRecord>,
    pub stream_records: Vec<StreamRecord>,
}

struct Combo {
    framework: FrameworkKey,
    mode: ThreadMode,
    label: String,
    short: String,
}

fn combos(cores: usize) -> Vec<Combo> {
    vec![
        Combo { framework: FrameworkKey::Ossido, mode: ThreadMode::Single, label: "Ossido (1 thread)".into(), short: "Ossido ×1".into() },
        Combo { framework: FrameworkKey::Ossido, mode: ThreadMode::Multi, label: format!("Ossido ({cores} threads)"), short: format!("Ossido ×{cores}") },
        Combo { framework: FrameworkKey::Next, mode: ThreadMode::Single, label: "Next.js (1 process)".into(), short: "Next ×1".into() },
        Combo { framework: FrameworkKey::Next, mode: ThreadMode::Multi, label: format!("Next.js ({cores} processes)"), short: format!("Next ×{cores}") },
    ]
}

fn load_key(fw: FrameworkKey, mode: ThreadMode, scenario: &str) -> String {
    format!("{}|{}|{}", fw.as_str(), mode.as_str(), scenario)
}
fn stream_key(fw: FrameworkKey, mode: ThreadMode) -> String {
    format!("{}|{}", fw.as_str(), mode.as_str())
}

/// Round to `digits` decimals with en-US comma grouping (mirrors `toLocaleString`).
pub fn fmt(n: f64, digits: usize) -> String {
    let neg = n < 0.0;
    let s = format!("{:.*}", digits, n.abs());
    let (int_part, frac) = match s.split_once('.') {
        Some((i, f)) => (i.to_string(), Some(f.to_string())),
        None => (s, None),
    };
    let mut out = String::new();
    if neg {
        out.push('-');
    }
    out.push_str(&group_thousands(&int_part));
    if let Some(f) = frac {
        out.push('.');
        out.push_str(&f);
    }
    out
}

fn group_thousands(int_part: &str) -> String {
    let bytes = int_part.as_bytes();
    let len = bytes.len();
    let mut out = String::with_capacity(len + len / 3);
    for (i, b) in bytes.iter().enumerate() {
        if i > 0 && (len - i) % 3 == 0 {
            out.push(',');
        }
        out.push(*b as char);
    }
    out
}

fn round2(v: f64) -> f64 {
    if v.is_finite() {
        (v * 100.0).round() / 100.0
    } else {
        0.0
    }
}

/// Emit a mermaid `xychart-beta` bar chart. Labels are normalized to ASCII `x`
/// (the mermaid grammar rejects U+00D7).
pub fn mermaid_bar(title: &str, y_label: &str, labels: &[String], values: &[f64]) -> String {
    let xs = labels
        .iter()
        .map(|l| format!("\"{}\"", l.replace('×', "x")))
        .collect::<Vec<_>>()
        .join(", ");
    let ys = values.iter().map(|v| round2(*v).to_string()).collect::<Vec<_>>().join(", ");
    [
        "```mermaid",
        "xychart-beta",
        &format!("    title \"{title}\""),
        &format!("    x-axis [{xs}]"),
        &format!("    y-axis \"{y_label}\""),
        &format!("    bar [{ys}]"),
        "```",
        "",
    ]
    .join("\n")
}

pub fn results_markdown(report: &BenchReport) -> String {
    let cores = report.cores;
    let cs = combos(cores);
    let scenarios = load_scenarios();
    let stream = stream_scenario();

    let load: HashMap<String, &LoadRecord> = report
        .load_records
        .iter()
        .map(|r| (load_key(r.framework, r.mode, &r.scenario), r))
        .collect();
    let streams: HashMap<String, &StreamRecord> = report
        .stream_records
        .iter()
        .map(|r| (stream_key(r.framework, r.mode), r))
        .collect();

    let mut lines: Vec<String> = Vec::new();
    let mut p = |s: String| lines.push(s);

    p("# Ossido vs Next.js — SSR benchmark".into());
    p(String::new());
    p("> Generated by `bun run bench`. Both apps render **byte-for-byte identical**".into());
    p("> React trees from identical data, so differences reflect the runtime, not the".into());
    p("> workload. Ossido renders through a multi-threaded V8 render pool embedded in a".into());
    p("> Rust/axum server; Next.js runs on Node.js, scaled across cores with the".into());
    p("> `cluster` module. Higher req/s is better; lower latency is better.".into());
    p(String::new());
    p("## Environment".into());
    p(String::new());
    p("| | |".into());
    p("| --- | --- |".into());
    p(format!("| Date | {} |", report.generated_at));
    p(format!("| Host | {} |", report.host));
    p(format!("| CPU | {} |", report.cpu_model));
    p(format!("| Logical cores | {cores} |"));
    p(format!("| Memory | {} GB |", report.total_mem_gb));
    p(format!("| Versions | Ossido {}, Next.js {} |", report.versions.ossido, report.versions.next));
    p(format!(
        "| Load | {} connections, {}s per scenario (heavy-table render uses fewer — see per-scenario `Conns` below) |",
        report.connections, report.duration_sec
    ));
    p(String::new());

    // ---- Throughput summary ----
    p("## Throughput (req/s — higher is better)".into());
    p(String::new());
    p(format!("| Scenario | {} |", cs.iter().map(|c| c.short.clone()).collect::<Vec<_>>().join(" | ")));
    p(format!("| --- | {} |", cs.iter().map(|_| "---:").collect::<Vec<_>>().join(" | ")));
    for s in &scenarios {
        let cells: Vec<String> = cs
            .iter()
            .map(|c| load.get(&load_key(c.framework, c.mode, s.key)).map(|r| fmt(r.result.rps, 0)).unwrap_or_else(|| "—".into()))
            .collect();
        p(format!("| {} | {} |", s.title, cells.join(" | ")));
    }
    p(String::new());

    // ---- p99 latency summary ----
    p("## p99 latency (ms — lower is better)".into());
    p(String::new());
    p(format!("| Scenario | {} |", cs.iter().map(|c| c.short.clone()).collect::<Vec<_>>().join(" | ")));
    p(format!("| --- | {} |", cs.iter().map(|_| "---:").collect::<Vec<_>>().join(" | ")));
    for s in &scenarios {
        let cells: Vec<String> = cs
            .iter()
            .map(|c| load.get(&load_key(c.framework, c.mode, s.key)).map(|r| fmt(r.result.latency_p99, 1)).unwrap_or_else(|| "—".into()))
            .collect();
        p(format!("| {} | {} |", s.title, cells.join(" | ")));
    }
    p(String::new());

    // ---- Detailed metrics ----
    p("## Detailed metrics".into());
    p(String::new());
    p("| Scenario | Config | Conns | req/s | p50 (ms) | p99 (ms) | Throughput (MB/s) | Errors |".into());
    p("| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |".into());
    for s in &scenarios {
        for c in &cs {
            if let Some(r) = load.get(&load_key(c.framework, c.mode, s.key)) {
                p(format!(
                    "| {} | {} | {} | {} | {} | {} | {} | {} |",
                    s.title,
                    c.label,
                    r.result.connections,
                    fmt(r.result.rps, 0),
                    fmt(r.result.latency_p50, 2),
                    fmt(r.result.latency_p99, 2),
                    fmt(r.result.throughput_mbps, 1),
                    r.result.errors
                ));
            }
        }
    }
    p(String::new());

    // ---- Charts per scenario ----
    p("## Charts".into());
    p(String::new());
    for s in &scenarios {
        let labels: Vec<String> = cs.iter().map(|c| c.short.clone()).collect();
        let values: Vec<f64> = cs.iter().map(|c| load.get(&load_key(c.framework, c.mode, s.key)).map(|r| r.result.rps).unwrap_or(0.0)).collect();
        p(format!("### {} — throughput", s.title));
        p(String::new());
        p(format!("*{}.*", s.note));
        p(String::new());
        p(mermaid_bar(&format!("{} — req/s (higher is better)", s.title), "req/s", &labels, &values));
    }

    // ---- Multi-core scaling ----
    p(format!("### Multi-core scaling (req/s: 1 → {cores} threads)"));
    p(String::new());
    p("How each framework scales from single-threaded to all cores on the CPU-bound".into());
    p("heavy-table render.".into());
    p(String::new());
    for fw in [FrameworkKey::Ossido, FrameworkKey::Next] {
        let single = load.get(&load_key(fw, ThreadMode::Single, "heavy")).map(|r| r.result.rps).unwrap_or(0.0);
        let multi = load.get(&load_key(fw, ThreadMode::Multi, "heavy")).map(|r| r.result.rps).unwrap_or(0.0);
        let speedup = if single > 0.0 { format!("{:.2}", multi / single) } else { "—".into() };
        let name = if fw == FrameworkKey::Ossido { "Ossido" } else { "Next.js" };
        p(format!("- **{name}**: {} → {} req/s (**{speedup}×**)", fmt(single, 0), fmt(multi, 0)));
    }
    p(String::new());
    {
        let labels: Vec<String> = cs.iter().map(|c| c.short.clone()).collect();
        let values: Vec<f64> = cs.iter().map(|c| load.get(&load_key(c.framework, c.mode, "heavy")).map(|r| r.result.rps).unwrap_or(0.0)).collect();
        p(mermaid_bar("Heavy-table render — scaling across cores (req/s)", "req/s", &labels, &values));
    }

    // ---- Streaming ----
    p("## Streaming SSR (time-to-first-byte vs full response)".into());
    p(String::new());
    p(format!("*{}. Lower TTFB means the browser can start painting the", stream.note));
    p("shell sooner while the server streams the rest.*".into());
    p(String::new());
    p("| Config | TTFB (ms) | Total (ms) | Streamed after shell (ms) |".into());
    p("| --- | ---: | ---: | ---: |".into());
    for c in &cs {
        if let Some(r) = streams.get(&stream_key(c.framework, c.mode)) {
            let gap = r.result.total_ms - r.result.ttfb_ms;
            p(format!("| {} | {} | {} | {} |", c.label, fmt(r.result.ttfb_ms, 1), fmt(r.result.total_ms, 1), fmt(gap, 1)));
        }
    }
    p(String::new());
    {
        let labels: Vec<String> = cs.iter().map(|c| c.short.clone()).collect();
        let ttfb: Vec<f64> = cs.iter().map(|c| streams.get(&stream_key(c.framework, c.mode)).map(|r| r.result.ttfb_ms).unwrap_or(0.0)).collect();
        p(mermaid_bar("Streaming — time-to-first-byte (ms, lower is better)", "ms", &labels, &ttfb));
    }

    p("---".into());
    p(String::new());
    p("### How this is measured".into());
    p(String::new());
    p("- **Load generator:** a built-in Rust/tokio load generator".into());
    p(format!(
        "  ({} connections, {}s per scenario, after a warm-up pass; the CPU-bound heavy-table render uses fewer connections so a saturated queue does not exceed the request timeout).",
        report.connections, report.duration_sec
    ));
    p("- **Single-threaded:** Ossido with `OSSIDO_SSR_THREADS=1`; Next.js as a single".into());
    p("  Node process.".into());
    p(format!("- **Multi-threaded:** Ossido with `OSSIDO_SSR_THREADS={cores}` (one V8 render"));
    p(format!("  isolate per core); Next.js as a {cores}-worker `cluster` on one shared port."));
    p("- **Streaming** is probed sequentially, timing the first streamed chunk (shell)".into());
    p("  separately from the full response.".into());
    p("- Both apps are production builds (`ossido build` + `cargo build --release`,".into());
    p("  `next build`) and render the identical component tree from `src/bench/`.".into());
    p(String::new());

    lines.join("\n")
}

// ── JSON (schema ossido-benchmark/results@1) ────────────────────────────────

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct Environment {
    host: String,
    cpu: String,
    cores: usize,
    total_mem_gb: f64,
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct LoadMeta {
    connections: usize,
    duration_sec: u64,
    warmup_sec: u64,
}

#[derive(Serialize)]
struct ScenarioJson {
    key: &'static str,
    title: &'static str,
    path: &'static str,
    note: &'static str,
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct ResultJson {
    framework: &'static str,
    mode: &'static str,
    threads: usize,
    scenario: String,
    connections: usize,
    rps: f64,
    latency_mean_ms: f64,
    latency_p50_ms: f64,
    latency_p99_ms: f64,
    throughput_mbps: f64,
    errors: u64,
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct StreamingJson {
    framework: &'static str,
    mode: &'static str,
    threads: usize,
    ttfb_ms: f64,
    total_ms: f64,
    bytes: u64,
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct ResultsJson {
    schema: &'static str,
    generated_at: String,
    environment: Environment,
    versions: Versions,
    load: LoadMeta,
    scenarios: Vec<ScenarioJson>,
    results: Vec<ResultJson>,
    streaming: Vec<StreamingJson>,
}

pub fn results_json(report: &BenchReport) -> Result<String> {
    let mut scenarios: Vec<ScenarioJson> = load_scenarios()
        .iter()
        .map(|s| ScenarioJson { key: s.key, title: s.title, path: s.path, note: s.note })
        .collect();
    let stream = stream_scenario();
    scenarios.push(ScenarioJson { key: stream.key, title: stream.title, path: stream.path, note: stream.note });

    let json = ResultsJson {
        schema: "ossido-benchmark/results@1",
        generated_at: report.generated_at.clone(),
        environment: Environment {
            host: report.host.clone(),
            cpu: report.cpu_model.clone(),
            cores: report.cores,
            total_mem_gb: report.total_mem_gb,
        },
        versions: report.versions.clone(),
        load: LoadMeta {
            connections: report.connections,
            duration_sec: report.duration_sec,
            warmup_sec: report.warmup_sec,
        },
        scenarios,
        results: report
            .load_records
            .iter()
            .map(|r| ResultJson {
                framework: r.framework.as_str(),
                mode: r.mode.as_str(),
                threads: r.threads,
                scenario: r.scenario.clone(),
                connections: r.result.connections,
                rps: r.result.rps,
                latency_mean_ms: r.result.latency_mean,
                latency_p50_ms: r.result.latency_p50,
                latency_p99_ms: r.result.latency_p99,
                throughput_mbps: r.result.throughput_mbps,
                errors: r.result.errors,
            })
            .collect(),
        streaming: report
            .stream_records
            .iter()
            .map(|r| StreamingJson {
                framework: r.framework.as_str(),
                mode: r.mode.as_str(),
                threads: r.threads,
                ttfb_ms: r.result.ttfb_ms,
                total_ms: r.result.total_ms,
                bytes: r.result.bytes,
            })
            .collect(),
    };
    Ok(serde_json::to_string_pretty(&json)? + "\n")
}
