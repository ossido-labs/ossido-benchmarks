import { writeFile } from 'node:fs/promises';
import { LOAD_SCENARIOS, STREAM_SCENARIO, type ThreadMode } from './config.ts';
import type { LoadRecord, StreamRecord } from './run.ts';

export interface BenchReport {
  generatedAt: string;
  cores: number;
  host: string;
  cpuModel: string;
  totalMemGb: number;
  connections: number;
  durationSec: number;
  loadRecords: LoadRecord[];
  streamRecords: StreamRecord[];
}

interface Combo {
  framework: 'ossido' | 'next';
  mode: ThreadMode;
  label: string;
  short: string;
}

function combos(cores: number): Combo[] {
  return [
    { framework: 'ossido', mode: 'single', label: 'Ossido (1 thread)', short: 'Ossido ×1' },
    { framework: 'ossido', mode: 'multi', label: `Ossido (${cores} threads)`, short: `Ossido ×${cores}` },
    { framework: 'next', mode: 'single', label: 'Next.js (1 process)', short: 'Next ×1' },
    { framework: 'next', mode: 'multi', label: `Next.js (${cores} processes)`, short: `Next ×${cores}` },
  ];
}

const loadKey = (fw: string, mode: string, scenario: string): string => `${fw}|${mode}|${scenario}`;
const streamKey = (fw: string, mode: string): string => `${fw}|${mode}`;

function fmt(n: number, digits = 0): string {
  return n.toLocaleString('en-US', { minimumFractionDigits: digits, maximumFractionDigits: digits });
}

function mermaidBar(title: string, yLabel: string, labels: string[], values: number[]): string {
  // NB: use ASCII 'x' (not '×') — the mermaid grammar rejects U+00D7 in labels.
  const xs = labels.map((l) => `"${l.replace(/×/g, 'x')}"`).join(', ');
  const ys = values.map((v) => (Number.isFinite(v) ? Math.round(v * 100) / 100 : 0)).join(', ');
  return [
    '```mermaid',
    'xychart-beta',
    `    title "${title}"`,
    `    x-axis [${xs}]`,
    `    y-axis "${yLabel}"`,
    `    bar [${ys}]`,
    '```',
    '',
  ].join('\n');
}

export async function writeReport(report: BenchReport, outPath: string): Promise<void> {
  const { cores, loadRecords, streamRecords } = report;
  const cs = combos(cores);

  const load = new Map<string, LoadRecord>();
  for (const r of loadRecords) load.set(loadKey(r.framework, r.mode, r.scenario), r);
  const stream = new Map<string, StreamRecord>();
  for (const r of streamRecords) stream.set(streamKey(r.framework, r.mode), r);

  const lines: string[] = [];
  const p = (s = ''): void => void lines.push(s);

  p('# Ossido vs Next.js — SSR benchmark');
  p();
  p('> Generated by `bun run bench`. Both apps render **byte-for-byte identical**');
  p('> React trees from identical data, so differences reflect the runtime, not the');
  p('> workload. Ossido renders through a multi-threaded V8 render pool embedded in a');
  p('> Rust/axum server; Next.js runs on Node.js, scaled across cores with the');
  p('> `cluster` module. Higher req/s is better; lower latency is better.');
  p();
  p('## Environment');
  p();
  p('| | |');
  p('| --- | --- |');
  p(`| Date | ${report.generatedAt} |`);
  p(`| Host | ${report.host} |`);
  p(`| CPU | ${report.cpuModel} |`);
  p(`| Logical cores | ${cores} |`);
  p(`| Memory | ${report.totalMemGb} GB |`);
  p(
    `| Load | ${report.connections} connections, ${report.durationSec}s per scenario ` +
      `(heavy-table render uses fewer — see per-scenario \`Conns\` below) |`,
  );
  p();

  // ---- Throughput summary table ----
  p('## Throughput (req/s — higher is better)');
  p();
  p(`| Scenario | ${cs.map((c) => c.short).join(' | ')} |`);
  p(`| --- | ${cs.map(() => '---:').join(' | ')} |`);
  for (const s of LOAD_SCENARIOS) {
    const cells = cs.map((c) => {
      const r = load.get(loadKey(c.framework, c.mode, s.key));
      return r ? fmt(r.result.rps) : '—';
    });
    p(`| ${s.title} | ${cells.join(' | ')} |`);
  }
  p();

  // ---- p99 latency summary ----
  p('## p99 latency (ms — lower is better)');
  p();
  p(`| Scenario | ${cs.map((c) => c.short).join(' | ')} |`);
  p(`| --- | ${cs.map(() => '---:').join(' | ')} |`);
  for (const s of LOAD_SCENARIOS) {
    const cells = cs.map((c) => {
      const r = load.get(loadKey(c.framework, c.mode, s.key));
      return r ? fmt(r.result.latencyP99, 1) : '—';
    });
    p(`| ${s.title} | ${cells.join(' | ')} |`);
  }
  p();

  // ---- Detailed metrics ----
  p('## Detailed metrics');
  p();
  p('| Scenario | Config | Conns | req/s | p50 (ms) | p99 (ms) | Throughput (MB/s) | Errors |');
  p('| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |');
  for (const s of LOAD_SCENARIOS) {
    for (const c of cs) {
      const r = load.get(loadKey(c.framework, c.mode, s.key));
      if (!r) continue;
      p(
        `| ${s.title} | ${c.label} | ${r.result.connections} | ${fmt(r.result.rps)} | ${fmt(r.result.latencyP50, 2)} | ` +
          `${fmt(r.result.latencyP99, 2)} | ${fmt(r.result.throughputMbps, 1)} | ${r.result.errors} |`,
      );
    }
  }
  p();

  // ---- Charts per scenario ----
  p('## Charts');
  p();
  for (const s of LOAD_SCENARIOS) {
    const labels = cs.map((c) => c.short);
    const values = cs.map((c) => load.get(loadKey(c.framework, c.mode, s.key))?.result.rps ?? 0);
    p(`### ${s.title} — throughput`);
    p();
    p(`*${s.note}.*`);
    p();
    p(mermaidBar(`${s.title} — req/s (higher is better)`, 'req/s', labels, values));
  }

  // ---- Multi-core scaling ----
  p('### Multi-core scaling (req/s: 1 → ' + cores + ' threads)');
  p();
  p('How each framework scales from single-threaded to all cores on the CPU-bound');
  p('heavy-table render.');
  p();
  for (const fwKey of ['ossido', 'next'] as const) {
    const single = load.get(loadKey(fwKey, 'single', 'heavy'))?.result.rps ?? 0;
    const multi = load.get(loadKey(fwKey, 'multi', 'heavy'))?.result.rps ?? 0;
    const speedup = single > 0 ? (multi / single).toFixed(2) : '—';
    const name = fwKey === 'ossido' ? 'Ossido' : 'Next.js';
    p(`- **${name}**: ${fmt(single)} → ${fmt(multi)} req/s (**${speedup}×**)`);
  }
  p();
  {
    const labels = cs.map((c) => c.short);
    const values = cs.map((c) => load.get(loadKey(c.framework, c.mode, 'heavy'))?.result.rps ?? 0);
    p(mermaidBar('Heavy-table render — scaling across cores (req/s)', 'req/s', labels, values));
  }

  // ---- Streaming ----
  p('## Streaming SSR (time-to-first-byte vs full response)');
  p();
  p(`*${STREAM_SCENARIO.note}. Lower TTFB means the browser can start painting the`);
  p('shell sooner while the server streams the rest.*');
  p();
  p('| Config | TTFB (ms) | Total (ms) | Streamed after shell (ms) |');
  p('| --- | ---: | ---: | ---: |');
  for (const c of cs) {
    const r = stream.get(streamKey(c.framework, c.mode));
    if (!r) continue;
    const gap = r.result.totalMs - r.result.ttfbMs;
    p(
      `| ${c.label} | ${fmt(r.result.ttfbMs, 1)} | ${fmt(r.result.totalMs, 1)} | ${fmt(gap, 1)} |`,
    );
  }
  p();
  {
    const labels = cs.map((c) => c.short);
    const ttfb = cs.map((c) => stream.get(streamKey(c.framework, c.mode))?.result.ttfbMs ?? 0);
    p(mermaidBar('Streaming — time-to-first-byte (ms, lower is better)', 'ms', labels, ttfb));
  }

  p('---');
  p();
  p('### How this is measured');
  p();
  p('- **Load generator:** [autocannon](https://github.com/mcollina/autocannon)');
  p(
    `  (${report.connections} connections, ${report.durationSec}s per scenario, after a warm-up pass; ` +
      'the CPU-bound heavy-table render uses fewer connections so a saturated ' +
      'queue does not exceed the request timeout).',
  );
  p('- **Single-threaded:** Ossido with `OSSIDO_SSR_THREADS=1`; Next.js as a single');
  p('  Node process.');
  p(`- **Multi-threaded:** Ossido with \`OSSIDO_SSR_THREADS=${cores}\` (one V8 render`);
  p(`  isolate per core); Next.js as a ${cores}-worker \`cluster\` on one shared port.`);
  p('- **Streaming** is probed sequentially, timing the first streamed chunk (shell)');
  p('  separately from the full response.');
  p('- Both apps are production builds (`ossido build` + `cargo build --release`,');
  p('  `next build`) and render the identical component tree from `src/bench/`.');
  p();

  await writeFile(outPath, lines.join('\n'));
}
